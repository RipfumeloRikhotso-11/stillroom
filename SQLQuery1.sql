CREATE DATABASE StillroomDB;
GO

USE StillroomDB;
GO

DROP TABLE IF EXISTS SESSION_TASK;
DROP TABLE IF EXISTS FOCUS_SESSION;
DROP TABLE IF EXISTS APP_SETTINGS;
DROP TABLE IF EXISTS USERS;
DROP TABLE IF EXISTS ContactMessage;
GO

-- 1. USERS TABLE
CREATE TABLE USERS (
    UserID INT IDENTITY(1,1) NOT NULL,
    FullName VARCHAR(100) NOT NULL,
    Email VARCHAR(255) NOT NULL,
    PasswordHash VARCHAR(500) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    IsActive BIT NOT NULL DEFAULT 1,

    CONSTRAINT PK_USERS PRIMARY KEY (UserID),
    CONSTRAINT UQ_USERS_Email UNIQUE (Email)
);
GO

-- 2. FOCUS SESSION TABLE
CREATE TABLE FOCUS_SESSION (
    SessionID INT IDENTITY(1,1) NOT NULL,
    UserID INT NOT NULL,
    SessionGoal VARCHAR(200) NOT NULL,
    DurationMinutes INT NOT NULL,
    StartedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CompletedAt DATETIME2 NULL,

    CONSTRAINT PK_FOCUS_SESSION
        PRIMARY KEY (SessionID),

    CONSTRAINT FK_FOCUS_SESSION_USERS
        FOREIGN KEY (UserID)
        REFERENCES USERS(UserID),

    CONSTRAINT CK_FOCUS_SESSION_DURATION
        CHECK (DurationMinutes > 0)
);
GO

-- 3. SESSION TASK TABLE
CREATE TABLE SESSION_TASK (
    TaskID INT IDENTITY(1,1) NOT NULL,
    SessionID INT NOT NULL,
    TaskDescription VARCHAR(200) NOT NULL,
    IsComplete BIT NOT NULL DEFAULT 0,
    TaskPosition INT NOT NULL DEFAULT 1,

    CONSTRAINT PK_SESSION_TASK
        PRIMARY KEY (TaskID),

    CONSTRAINT FK_SESSION_TASK_FOCUS_SESSION
        FOREIGN KEY (SessionID)
        REFERENCES FOCUS_SESSION(SessionID)
        ON DELETE CASCADE,

    CONSTRAINT CK_SESSION_TASK_POSITION
        CHECK (TaskPosition > 0)
);
GO

-- 4. APP SETTINGS TABLE
CREATE TABLE APP_SETTINGS (
    SettingsID INT IDENTITY(1,1) NOT NULL,
    UserID INT NOT NULL,
    TimerMinutes INT NOT NULL DEFAULT 25,
    AmbientSound VARCHAR(20) NOT NULL DEFAULT 'rain',
    Volume INT NOT NULL DEFAULT 30,

    CONSTRAINT PK_APP_SETTINGS
        PRIMARY KEY (SettingsID),

    CONSTRAINT UQ_APP_SETTINGS_UserID
        UNIQUE (UserID),

    CONSTRAINT FK_APP_SETTINGS_USERS
        FOREIGN KEY (UserID)
        REFERENCES USERS(UserID)
        ON DELETE CASCADE,

    CONSTRAINT CK_APP_SETTINGS_TIMER
        CHECK (TimerMinutes IN (25, 45, 60)),

    CONSTRAINT CK_APP_SETTINGS_SOUND
        CHECK (AmbientSound IN ('rain', 'cafe', 'forest', 'off')),

    CONSTRAINT CK_APP_SETTINGS_VOLUME
        CHECK (Volume BETWEEN 0 AND 100)
);
GO

-- 5. INDEXES
CREATE INDEX IX_FOCUS_SESSION_UserID_CompletedAt
    ON FOCUS_SESSION(UserID, CompletedAt);

CREATE INDEX IX_SESSION_TASK_SessionID_TaskPosition
    ON SESSION_TASK(SessionID, TaskPosition);
GO

CREATE TABLE ContactMessage
(
    MessageID INT IDENTITY(1,1) PRIMARY KEY,
    FullName NVARCHAR(100) NOT NULL,
    Email NVARCHAR(254) NOT NULL,
    Subject NVARCHAR(150) NOT NULL,
    MessageText NVARCHAR(2000) NOT NULL,
    SubmittedAt DATETIME NOT NULL
        CONSTRAINT DF_ContactMessage_SubmittedAt
        DEFAULT GETDATE()
);
GO

SELECT *
FROM ContactMessage
ORDER BY SubmittedAt DESC;